/**
 * `npm run traceability` — regenerates docs/requirements-traceability.md.
 *
 * WHY this is generated rather than hand-written: a traceability matrix that is typed by hand drifts
 * from the code within a week, and a stale matrix is worse than none because it looks authoritative.
 * The rows are derived from the JSON Schema in content/profile.schema.json plus the feature table in
 * docs/PROGRESS.md, so editing either and re-running keeps it honest.
 *
 * WHY a requirement has no test and says so: AGENTS.md forbids claiming coverage that does not exist.
 * An empty "verified by" cell is information; a fabricated test name is a lie with a table format.
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'docs', 'requirements-traceability.md');
const PROGRESS = join(ROOT, 'docs', 'PROGRESS.md');

/** Pulls the feature-status table out of PROGRESS.md so the two docs cannot disagree. */
function parseFeatureTable(markdown) {
  const rows = [];
  for (const line of markdown.split('\n')) {
    const m = /^\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|/.exec(line);
    if (!m) continue;
    const [, feature, status, evidence] = m;
    if (feature === 'Feature' || /^-+$/.test(feature)) continue;
    rows.push({ feature, status, evidence });
  }
  return rows;
}

/** Collects test files so the matrix can point at real suites, not invented ones. */
function testFiles() {
  const found = [];
  const roots = ['tests', 'services/gateway/tests', 'services/ai/tests'];
  for (const r of roots) {
    const dir = join(ROOT, r);
    if (!existsSync(dir)) continue;
    for (const f of readdirSync(dir)) {
      if (/\.(test\.js|spec\.ts|py)$/.test(f)) found.push(`${r}/${f}`);
    }
  }
  return found.sort();
}

const progress = readFileSync(PROGRESS, 'utf8');
const features = parseFeatureTable(progress);
const tests = testFiles();

if (features.length === 0) {
  console.error(
    'traceability: found no feature table in docs/PROGRESS.md. '
    + 'Expected a markdown table with Feature | Status | Evidence columns.',
  );
  process.exit(1);
}

const counts = features.reduce((acc, f) => {
  acc[f.status] = (acc[f.status] ?? 0) + 1;
  return acc;
}, {});

const lines = [
  '# Requirements traceability',
  '',
  '<!-- GENERATED by `npm run traceability`. Do not edit by hand: edits are overwritten. -->',
  '',
  `Generated from \`docs/PROGRESS.md\` and the working tree on ${new Date().toISOString().slice(0, 10)}.`,
  '',
  '## Status summary',
  '',
  '| Status | Count |',
  '| --- | --- |',
  ...Object.entries(counts).sort().map(([s, n]) => `| ${s} | ${n} |`),
  '',
  `Total features: **${features.length}**. Test files discovered: **${tests.length}**.`,
  '',
  '## Feature matrix',
  '',
  '| Feature | Status | Evidence (as recorded in PROGRESS.md) |',
  '| --- | --- | --- |',
  ...features.map((f) => `| ${f.feature} | ${f.status} | ${f.evidence} |`),
  '',
  '## Test suites',
  '',
  ...tests.map((t) => `- \`${t}\``),
  '',
  '## How to read this',
  '',
  '- **Implemented** means tested and passing in `npm run verify`.',
  '- **Partial** means some layers are verified and others are not; the evidence cell says which.',
  '- **Not Implemented** is listed, never omitted. A missing row would misrepresent the project.',
  '- Re-run `npm run traceability` after changing this table; the matrix is derived, not authored.',
  '',
];

writeFileSync(OUT, lines.join('\n'), 'utf8');
console.log(`traceability: wrote ${relative(ROOT, OUT)} (${features.length} features, ${tests.length} test files)`);